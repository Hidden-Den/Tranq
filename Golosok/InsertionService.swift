import Foundation
import AppKit
import Carbon

public struct FocusSnapshot: Equatable {
    public let pid: pid_t
    public let bundleIdentifier: String?
    public let appName: String
    public let focusedRole: String?
    public let capturedAt: Date

    public init(pid: pid_t, bundleIdentifier: String?, appName: String, focusedRole: String? = nil, capturedAt: Date = Date()) {
        self.pid = pid
        self.bundleIdentifier = bundleIdentifier
        self.appName = appName
        self.focusedRole = focusedRole
        self.capturedAt = capturedAt
    }
}

public enum InsertionResult: Equatable {
    case pasted
    case copied
    case focusChanged(targetAppName: String, currentAppName: String)
    case secureInput(appName: String)
    case accessibilityDenied
}

public final class InsertionService {
    public static let shared = InsertionService()

    private init() {}

    /// Снимок фокуса приложения и текстового элемента в момент завершения записи
    public func captureFocus() -> FocusSnapshot? {
        guard let app = NSWorkspace.shared.frontmostApplication else { return nil }
        let pid = app.processIdentifier
        let role = detectFocusedRole(pid: pid)
        return FocusSnapshot(
            pid: pid,
            bundleIdentifier: app.bundleIdentifier,
            appName: app.localizedName ?? "App",
            focusedRole: role
        )
    }

    /// Проверка, активно ли защищенное поле пароля (Secure Input)
    public var isSecureInputActive: Bool {
        IsSecureEventInputEnabled()
    }

    /// Помещение текста в буфер с системными флагами transient (скрытие из менеджеров буфера)
    public func copyToPasteboard(text: String, markTransient: Bool = true) {
        let pb = NSPasteboard.general
        pb.clearContents()

        if markTransient {
            let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
            let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
            let concealedType = NSPasteboard.PasteboardType("com.apple.metadata:kMDItemOMUserTags")
            pb.declareTypes([.string, transientType, autoGeneratedType, concealedType], owner: nil)
            pb.setString(text, forType: .string)
            pb.setString("1", forType: transientType)
            pb.setString("1", forType: autoGeneratedType)
        } else {
            pb.setString(text, forType: .string)
        }
    }

    /// Интеллектуальная вставка текста под курсор с проверкой фокуса и прав
    public func paste(
        text: String,
        target: FocusSnapshot?,
        autoPasteEnabled: Bool,
        completion: @escaping (InsertionResult) -> Void
    ) {
        guard autoPasteEnabled else {
            copyToPasteboard(text: text, markTransient: false)
            AppLogger.shared.info("Insertion", "Авто-вставка отключена — текст помещён в буфер обмена")
            completion(.copied)
            return
        }

        guard AXIsProcessTrusted() else {
            copyToPasteboard(text: text, markTransient: false)
            AppLogger.shared.warn("Insertion", "Доступ AX недоступен — текст скопирован в буфер")
            completion(.accessibilityDenied)
            return
        }

        guard let target = target else {
            copyToPasteboard(text: text, markTransient: false)
            AppLogger.shared.info("Insertion", "Целевое приложение не определено — текст скопирован в буфер")
            completion(.copied)
            return
        }

        // Проверяем, не переключил ли пользователь окно во время обработки
        if let currentApp = NSWorkspace.shared.frontmostApplication, currentApp.processIdentifier != target.pid {
            copyToPasteboard(text: text, markTransient: false)
            let currName = currentApp.localizedName ?? "App"
            AppLogger.shared.info("Insertion", "Фокус изменился: цель \(target.appName), текущее \(currName) — вставка отменена, текст в буфере")
            completion(.focusChanged(targetAppName: target.appName, currentAppName: currName))
            return
        }

        // Проверяем Secure Event Input (окно ввода паролей)
        if isSecureInputActive {
            copyToPasteboard(text: text, markTransient: true)
            AppLogger.shared.info("Insertion", "Активен Secure Event Input — ⌘V заблокирован ОС, текст в буфере")
            completion(.secureInput(appName: target.appName))
            return
        }

        // Проверяем, может ли фокусный элемент принять текст
        guard canAcceptPaste(pid: target.pid) else {
            copyToPasteboard(text: text, markTransient: false)
            AppLogger.shared.info("Insertion", "Под фокусом нет текстового поля в \(target.appName) — текст скопирован в буфер")
            completion(.copied)
            return
        }

        // Подготавливаем буфер обмена
        copyToPasteboard(text: text, markTransient: true)

        // Активируем целевое приложение и отправляем чистый Cmd+V
        if let targetApp = NSRunningApplication(processIdentifier: target.pid) {
            targetApp.activate(options: [.activateIgnoringOtherApps])
        }

        DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) {
            self.postCleanCommandV(to: target.pid)
            AppLogger.shared.info("Insertion", "⌘V успешно отправлен в \(target.appName)")
            completion(.pasted)
        }
    }

    // MARK: - Вспомогательные методы

    private func detectFocusedRole(pid: pid_t) -> String? {
        let app = AXUIElementCreateApplication(pid)
        var focusedRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &focusedRef) == .success,
              let focusedElement = focusedRef else { return nil }
        var roleRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(focusedElement as! AXUIElement, kAXRoleAttribute as CFString, &roleRef) == .success,
              let roleString = roleRef as? String else { return nil }
        return roleString
    }

    private func canAcceptPaste(pid: pid_t) -> Bool {
        guard let role = detectFocusedRole(pid: pid) else { return true }
        switch role {
        case "AXTextField", "AXTextArea", "AXTextView", "AXComboBox", "AXSearchField",
             "AXDocument", "AXScrollArea", "AXWebArea":
            return true
        default:
            return false
        }
    }

    private func postCleanCommandV(to pid: pid_t) {
        let source = CGEventSource(stateID: .combinedSessionState)
        // 0x09 = Virtual key code for 'V' on ANSI layout
        guard let keyDown = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true),
              let keyUp = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false) else { return }

        // Строго очищаем все флаги, оставляя только маску Command,
        // чтобы избежать случайного срабатывания ⌥⌘V или ⌃⌘V при зажатых модификаторах
        keyDown.flags = .maskCommand
        keyUp.flags = .maskCommand

        keyDown.postToPid(pid)
        keyUp.postToPid(pid)
    }
}
